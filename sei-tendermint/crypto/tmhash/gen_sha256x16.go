//go:build ignore

// gen_sha256x16 writes sha256x16_amd64.go: a fully unrolled 16-lane SHA-256
// compression over simd/archsimd Uint32x16 vectors. Each lane is one message;
// all lanes must have the same number of padded blocks.
//
// Usage: go run gen_sha256x16.go
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
)

var k = [64]uint32{
	0x428a2f98, 0x71374491, 0xb5c0fbcf, 0xe9b5dba5, 0x3956c25b, 0x59f111f1, 0x923f82a4, 0xab1c5ed5,
	0xd807aa98, 0x12835b01, 0x243185be, 0x550c7dc3, 0x72be5d74, 0x80deb1fe, 0x9bdc06a7, 0xc19bf174,
	0xe49b69c1, 0xefbe4786, 0x0fc19dc6, 0x240ca1cc, 0x2de92c6f, 0x4a7484aa, 0x5cb0a9dc, 0x76f988da,
	0x983e5152, 0xa831c66d, 0xb00327c8, 0xbf597fc7, 0xc6e00bf3, 0xd5a79147, 0x06ca6351, 0x14292967,
	0x27b70a85, 0x2e1b2138, 0x4d2c6dfc, 0x53380d13, 0x650a7354, 0x766a0abb, 0x81c2c92e, 0x92722c85,
	0xa2bfe8a1, 0xa81a664b, 0xc24b8b70, 0xc76c51a3, 0xd192e819, 0xd6990624, 0xf40e3585, 0x106aa070,
	0x19a4c116, 0x1e376c08, 0x2748774c, 0x34b0bcb5, 0x391c0cb3, 0x4ed8aa4a, 0x5b9cca4f, 0x682e6ff3,
	0x748f82ee, 0x78a5636f, 0x84c87814, 0x8cc70208, 0x90befffa, 0xa4506ceb, 0xbef9a3f7, 0xc67178f2,
}

var h0 = [8]uint32{
	0x6a09e667, 0xbb67ae85, 0x3c6ef372, 0xa54ff53a, 0x510e527f, 0x9b05688c, 0x1f83d9ab, 0x5be0cd19,
}

func main() {
	var b bytes.Buffer
	p := func(format string, args ...any) { fmt.Fprintf(&b, format+"\n", args...) }

	p("// Code generated by gen_sha256x16.go; DO NOT EDIT.")
	p("")
	p("//go:build goexperiment.simd && amd64")
	p("")
	p("package tmhash")
	p("")
	p(`import "simd/archsimd"`)
	p("")
	p("// sha256Block16 is one 64-byte block of each of 16 messages, laid out")
	p("// block16[word][lane] so that a word of every lane loads as one vector.")
	p("type sha256Block16 [16][16]uint32")
	p("")
	p("// Constants are kept pre-broadcast and loaded with LoadUint32x16Array;")
	p("// archsimd.BroadcastUint32x16 compiles to a legacy-SSE sequence that costs")
	p("// an SSE/AVX transition on every call.")
	p("var (")
	p("\tsha256K16 [64][16]uint32")
	p("\tsha256H16 [8][16]uint32")
	p(")")
	p("")
	p("func init() {")
	p("\tfor t, v := range [64]uint32{")
	for t := 0; t < 64; t += 8 {
		p("\t\t0x%08x, 0x%08x, 0x%08x, 0x%08x, 0x%08x, 0x%08x, 0x%08x, 0x%08x,",
			k[t], k[t+1], k[t+2], k[t+3], k[t+4], k[t+5], k[t+6], k[t+7])
	}
	p("\t} {")
	p("\t\tfor lane := range sha256K16[t] {")
	p("\t\t\tsha256K16[t][lane] = v")
	p("\t\t}")
	p("\t}")
	p("\tfor i, v := range [8]uint32{")
	p("\t\t0x%08x, 0x%08x, 0x%08x, 0x%08x, 0x%08x, 0x%08x, 0x%08x, 0x%08x,",
		h0[0], h0[1], h0[2], h0[3], h0[4], h0[5], h0[6], h0[7])
	p("\t} {")
	p("\t\tfor lane := range sha256H16[i] {")
	p("\t\t\tsha256H16[i][lane] = v")
	p("\t\t}")
	p("\t}")
	p("}")
	p("")
	p("// rotr32 rotates every lane right by n using VPSHRDD; RotateAllRight is")
	p("// emulated with three instructions.")
	p("func rotr32(x archsimd.Uint32x16, n uint64) archsimd.Uint32x16 {")
	p("\treturn x.ShiftAllRightConcatMod32(x, n)")
	p("}")
	p("")
	p("// sha256x16 compresses blocks, one sha256Block16 per message block, and")
	p("// writes the final state as out[word][lane] (big-endian digest words).")
	p("func sha256x16(blocks []sha256Block16, out *[8][16]uint32) {")
	for i := 0; i < 8; i++ {
		p("\th%d := archsimd.LoadUint32x16Array(&sha256H16[%d])", i, i)
	}
	p("\tfor bi := range blocks {")
	p("\t\tblk := &blocks[bi]")
	for t := 0; t < 16; t++ {
		p("\t\tw%d := archsimd.LoadUint32x16Array(&blk[%d])", t, t)
	}
	names := [8]string{"h0", "h1", "h2", "h3", "h4", "h5", "h6", "h7"}
	// Working variables a..h are renamed each round instead of shuffled.
	v := [8]string{"a", "b", "c", "d", "e", "f", "g", "h"}
	for i := range v {
		p("\t\t%s := %s", v[i], names[i])
	}
	p("\t\tvar t1, t2 archsimd.Uint32x16")
	for t := 0; t < 64; t++ {
		if t >= 16 {
			w16, w15, w7, w2 := t%16, (t-15)%16, (t-7)%16, (t-2)%16
			p("\t\tw%d = w%d.Add(rotr32(w%d, 7).Xor(rotr32(w%d, 18)).Xor(w%d.ShiftAllRight(3))).Add(w%d).Add(rotr32(w%d, 17).Xor(rotr32(w%d, 19)).Xor(w%d.ShiftAllRight(10)))",
				w16, w16, w15, w15, w15, w7, w2, w2, w2)
		}
		a, bb, c, d, e, f, g, hh := v[0], v[1], v[2], v[3], v[4], v[5], v[6], v[7]
		// T1 = h + Σ1(e) + Ch(e,f,g) + K[t] + W[t]
		p("\t\tt1 = %s.Add(rotr32(%s, 6).Xor(rotr32(%s, 11)).Xor(rotr32(%s, 25))).Add(%s.And(%s).Xor(%s.AndNot(%s))).Add(archsimd.LoadUint32x16Array(&sha256K16[%d])).Add(w%d)",
			hh, e, e, e, e, f, g, e, t, t%16)
		// T2 = Σ0(a) + Maj(a,b,c), Maj = (a&b) ^ ((a^b)&c)
		p("\t\tt2 = rotr32(%s, 2).Xor(rotr32(%s, 13)).Xor(rotr32(%s, 22)).Add(%s.And(%s).Xor(%s.Xor(%s).And(%s)))",
			a, a, a, a, bb, a, bb, c)
		// h <- g, g <- f, f <- e, e <- d+T1, d <- c, c <- b, b <- a, a <- T1+T2.
		// Rotating the names makes old h the new a and old d the new e.
		p("\t\t%s = %s.Add(t1)", d, d)
		p("\t\t%s = t1.Add(t2)", hh)
		v = [8]string{hh, a, bb, c, d, e, f, g}
	}
	for i := range v {
		p("\t\t%s = %s.Add(%s)", names[i], names[i], v[i])
	}
	p("\t}")
	for i := 0; i < 8; i++ {
		p("\th%d.StoreArray(&out[%d])", i, i)
	}
	p("}")

	src, err := format.Source(b.Bytes())
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	if err := os.WriteFile("sha256x16_amd64.go", src, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
