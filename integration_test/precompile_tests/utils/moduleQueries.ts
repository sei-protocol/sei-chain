/** The encode/decode half of a message type generated by `@sei-js/cosmos`. */
interface ProtoCodec<T> {
    encode(message: T): { finish(): Uint8Array };
    decode(input: Uint8Array): T;
}

/** A protobuf `Any`, as a module hands one back. */
export interface ProtoAny {
    type_url: string;
    value: Uint8Array;
}

// The ABCI answer for a value that does not exist: sei-cosmos maps a querier's
// gRPC NotFound onto the root codespace's ErrKeyNotFound (baseapp/abci.go,
// gRPCErrorToSDKError). Registered error codes are part of the query response,
// so this pair is as stable as the wire format itself.
const KEY_NOT_FOUND_CODESPACE = 'sdk';
const KEY_NOT_FOUND_CODE = 22;

/**
 * A module answered a query with an error code. This is distinct from a
 * transport failure: the chain was reached and the module declined.
 */
export class ModuleQueryError extends Error {
    constructor(
        readonly path: string,
        readonly code: number,
        readonly codespace: string,
        readonly log: string,
    ) {
        super(`${path} failed with code ${codespace}/${code}: ${log}`);
        this.name = 'ModuleQueryError';
    }

    /** True when the module reported that the queried value does not exist. */
    get notFound(): boolean {
        return this.codespace === KEY_NOT_FOUND_CODESPACE && this.code === KEY_NOT_FOUND_CODE;
    }
}

/**
 * Call `path` on a module's protobuf Query service at the latest height and
 * decode the reply. `path` is the gRPC method route
 * (`/cosmos.auth.v1beta1.Query/Params`). Throws ModuleQueryError when the
 * module declines the query.
 */
async function queryModule<Req, Res>(
    path: string,
    request: ProtoCodec<Req>,
    value: Req,
    response: ProtoCodec<Res>,
): Promise<Res> {
    const tm = await tendermintClient();
    const reply = await tm.abciQuery({
        path,
        data: request.encode(value).finish(),
        prove: false,
    });
    if (reply.code) {
        throw new ModuleQueryError(path, reply.code, reply.codespace, reply.log ?? '');
    }
    return response.decode(reply.value);
}

/**
 * An sdk.Dec in the fixed 18-decimal form the precompiles return
 * (`"0.050000000000000000"`). Protobuf carries a Dec as the digits of its
 * unscaled integer, so the decimal point has to be put back.
 */
export function decString(raw: Uint8Array | string): string {
    const encoded = typeof raw === 'string' ? raw : fromAscii(raw);
    const unscaled = encoded === '' ? '0' : encoded;
    const negative = unscaled.startsWith('-');
    const digits = (negative ? unscaled.slice(1) : unscaled).padStart(19, '0');
    return `${negative ? '-' : ''}${digits.slice(0, -18)}.${digits.slice(-18)}`;
}

/** Identity fields every account carries, however x/auth wraps them. */
export interface BaseAccountFields {
    address: string;
    account_number: number;
    sequence: number;
}

/** An account as x/auth stores it: base fields, possibly wrapped one or two deep. */
interface StoredAccount extends Partial<BaseAccountFields> {
    base_account?: StoredAccount;
    base_vesting_account?: StoredAccount;
}

const ACCOUNT_CODECS: ReadonlyArray<{ $type: string } & ProtoCodec<StoredAccount>> = [
    auth.BaseAccount,
    auth.ModuleAccount,
    vesting.BaseVestingAccount,
    vesting.ContinuousVestingAccount,
    vesting.DelayedVestingAccount,
    vesting.PeriodicVestingAccount,
    vesting.PermanentLockedAccount,
];

/**
 * The base account inside a stored account `Any`. Module and vesting accounts
 * nest theirs one or two levels down; the precompile reads through AccountI, so
 * it reports these fields for every account type and parity has to reach them.
 */
export function baseAccount(stored: ProtoAny): BaseAccountFields {
    const codec = ACCOUNT_CODECS.find(c => `/${c.$type}` === stored.type_url);
    if (codec === undefined) {
        throw new Error(
            `x/auth returned an account type this suite cannot decode: ${stored.type_url}`,
        );
    }
    let current: StoredAccount = codec.decode(stored.value);
    while (current.address === undefined) {
        const next = current.base_account ?? current.base_vesting_account;
        if (next === undefined) break;
        current = next;
    }
    return {
        address: current.address ?? '',
        account_number: current.account_number ?? 0,
        sequence: current.sequence ?? 0,
    };
}

/** The auth module's account for `seiAddress`, as the `Any` it is stored in. */
export async function authAccount(seiAddress: string): Promise<ProtoAny | undefined> {
    const { account } = await queryModule(
        '/cosmos.auth.v1beta1.Query/Account',
        auth.QueryAccountRequest,
        { address: seiAddress },
        auth.QueryAccountResponse,
    );
    return account;
}

