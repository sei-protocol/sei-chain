/**
 * The staking module's historical info for `height`, or undefined when the
 * module does not retain it. Only the module's own not-found answer reads as
 * undefined: a transport failure or any other module error still throws, so an
 * unreachable chain never reads as a chain that answered "not retained".
 */
export async function stakingHistoricalInfo(height: number) {
    try {
        const { hist } = await queryModule(
            '/cosmos.staking.v1beta1.Query/HistoricalInfo',
            staking.QueryHistoricalInfoRequest,
            { height },
            staking.QueryHistoricalInfoResponse,
        );
        return hist;
    } catch (e) {
        if (e instanceof ModuleQueryError && e.notFound) return undefined;
        throw e;
    }
}

