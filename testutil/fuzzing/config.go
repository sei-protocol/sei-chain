package fuzzing

import (
	"fmt"
	"math"
	"strconv"
	"strings"
	"unicode"
	"unicode/utf8"
)

// Go's native fuzzer only generates scalars: []byte, string, the sized numeric
// types, bool and rune. A configuration value, by contrast, is whatever viper
// hands back from a TOML document, an environment variable or a bound flag —
// a string, a bool, one of several numeric widths, a []any of tables, a nested
// map. The decoders here turn the scalars the fuzzer *can* produce into that
// shape deterministically, which is what makes a failing corpus entry
// reproducible: the same seed always decodes to the same value.

// ConfigValueKinds is the number of distinct shapes ConfigValue produces. A
// fuzz target reduces its kind selector modulo this so every generated byte maps
// onto a real shape instead of collapsing into one.
const ConfigValueKinds = 14

// ConfigValue decodes a fuzzer-supplied (kind, s, n, b) tuple into one candidate
// configuration value.
//
// The shapes are chosen to span what actually reaches a section reader in
// production, plus the shapes that break it:
//
//   - nil, twice over. An *absent* key and a key *present with a nil value* are
//     different inputs to `if v := opts.Get(k); v != nil`, and only the first
//     preserves the in-code default. Kind 0 is the present-but-nil case.
//   - strings, because TOML scalars and every environment variable arrive as
//     strings, and cast.ToBoolE("maybe") errors while cast.ToBool("maybe")
//     silently yields false.
//   - the numeric widths viper returns for TOML integers and floats, and
//     negatives among them. cast rejects a negative into any unsigned
//     conversion ("unable to cast negative value"), so a negative separates a
//     checked read — which fails the boot — from an unchecked one, which
//     silently resolves to 0.
//   - bools.
//   - []string and []any, the shapes ToStringSliceE accepts and rejects.
//   - map[string]any, what a TOML sub-table looks like when a key that should
//     hold a scalar is written as a section.
//   - the numeric-looking string and the "true"/"false" string, the two cases
//     where cast succeeds through a type the schema did not intend.
func ConfigValue(kind uint8, s string, n int64, b bool) any {
	switch kind % ConfigValueKinds {
	case 0:
		return nil
	case 1:
		return s
	case 2:
		return b
	case 3:
		return n
	case 4:
		return int(n)
	case 5:
		// Reinterpreting the sign bit yields a value near 2^64, which is what
		// exercises the overflow rejection in the narrower casts (ToInt, ToInt64,
		// ToUint32). A negative reaches a cast through kinds 3, 4 and 6 instead.
		return uint64(n) //nolint:gosec // the wrap is the input under test
	case 6:
		return float64(n) / 3
	case 7:
		return fmt.Sprintf("%d", n)
	case 8:
		if b {
			return "true"
		}
		return "false"
	case 9:
		return strings.Fields(s)
	case 10:
		return []any{s, n}
	case 11:
		return map[string]any{"nested": s}
	case 12:
		return []any{[]any{s, s}}
	default:
		return []string{}
	}
}

// ConfigValueKindName names the shape ConfigValue returns for a kind, for test
// output. A failure message that says "kind 5 (uint64)" is actionable; one that
// says "kind 5" is not.
func ConfigValueKindName(kind uint8) string {
	names := [ConfigValueKinds]string{
		"nil", "string", "bool", "int64", "int", "uint64", "float64",
		"numeric-string", "bool-string", "[]string", "[]any",
		"map[string]any", "[][]any", "empty-[]string",
	}
	return names[kind%ConfigValueKinds]
}

// tomlBasicStringSafe reports whether %q's rendering of s is also legal TOML.
//
// The safe set is deliberately narrow: valid UTF-8, and every rune either printable or one
// of the five whitespace escapes TOML and Go spell identically. That excludes exactly the
// cases where the two escape vocabularies diverge, which is what makes %q usable for
// everything it admits.
func tomlBasicStringSafe(s string) bool {
	if !utf8.ValidString(s) {
		return false
	}
	for _, r := range s {
		switch r {
		case '\b', '\t', '\n', '\f', '\r':
			continue
		}
		if !unicode.IsPrint(r) {
			return false
		}
	}
	return true
}

// TOMLScalar renders a value as the TOML text that would produce it, so a fuzz
// target can drive the same value through the file layer and the appOpts layer
// and compare. It returns ok=false for shapes with no single-line TOML spelling.
func TOMLScalar(v any) (string, bool) {
	switch t := v.(type) {
	case nil:
		return "", false
	case string:
		// %q renders Go escapes, and Go's set is wider than TOML's. TOML basic strings
		// accept only \b \t \n \f \r \" \\ \uXXXX and \UXXXXXXXX, so a control byte
		// rendered as \x01, a \v, or invalid UTF-8 rendered as \xNN all produce a
		// document the parser rejects. Returning it with ok=true would make the caller
		// attribute that parse failure to the layer under test, which for a differential
		// means a spurious divergence rather than a finding.
		//
		// Such a value is declined rather than escaped by hand. The point of this helper is
		// to put an identical value through two layers, so a value with no faithful TOML
		// spelling has nothing to contribute, and hand-rolling the escape set would add a
		// second encoder to keep correct.
		if !tomlBasicStringSafe(t) {
			return "", false
		}
		return fmt.Sprintf("%q", t), true
	case bool:
		return fmt.Sprintf("%t", t), true
	case int:
		return fmt.Sprintf("%d", t), true
	case int64:
		return fmt.Sprintf("%d", t), true
	case uint64:
		// TOML integers are signed 64-bit, so anything above MaxInt64 renders text the
		// parser rejects. ConfigValue's uint64 kind produces exactly that shape on purpose,
		// so a fuzzer reaches it as soon as this helper is wired to a target.
		if t > math.MaxInt64 {
			return "", false
		}
		return fmt.Sprintf("%d", t), true
	case float64:
		// TOML requires a fractional part or exponent on a float, and rejects the
		// Inf/NaN spellings Go prints.
		if t != t || t > 1e308 || t < -1e308 {
			return "", false
		}
		// An integral float keeps a fractional part, or TOML decodes the result as an
		// integer and the round trip changes the type: %g renders float64(3) as "3", which
		// parses back as int64(3). That matters for a differential comparing resolved types
		// across the file and appOpts layers.
		rendered := strconv.FormatFloat(t, 'g', -1, 64)
		if !strings.ContainsAny(rendered, ".eE") {
			rendered += ".0"
		}
		return rendered, true
	default:
		return "", false
	}
}
